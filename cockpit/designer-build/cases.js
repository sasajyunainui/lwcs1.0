function realCases(root) {
  const out = [];
  Object.entries(root.char).forEach(([角色名, 角色]) => {
    Object.entries(角色 || {}).forEach(([武魂槽, 武魂]) => {
      if (!/^第\d+武魂$/.test(武魂槽) || !武魂 || typeof 武魂 !== 'object') return;
      Object.entries(武魂).forEach(([魂灵槽, 魂灵]) => {
        if (!/^第\d+魂灵$/.test(魂灵槽) || !魂灵 || typeof 魂灵 !== 'object') return;
        Object.entries(魂灵).forEach(([环槽, 环]) => {
          if (!/^第\d+魂环$/.test(环槽) || !环 || typeof 环 !== 'object') return;
          Object.entries(环).forEach(([技键, 技]) => {
            if (!/魂技$/.test(技键) || !技 || !Array.isArray(技._效果数组)) return;
            out.push({ title: `${角色名}/${环槽}/${技.魂技名}`, meta: { path: ['char', 角色名, 武魂槽, 魂灵槽, 环槽, 技键], category: '魂环魂技', scope: '魂技' }, real: true });
          });
        });
      });
    });
  });
  return out;
}
